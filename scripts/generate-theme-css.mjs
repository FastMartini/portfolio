import { readFile, writeFile } from "node:fs/promises";

const tokens = JSON.parse(await readFile(new URL("../components/theme/tokens.json", import.meta.url), "utf8"));
const block = (selector, index) => {
  const values = [
    `  color-scheme: ${index ? "light" : "dark"};`,
    "  color: var(--ink);",
    ...Object.entries(tokens.surface).map(([key, pair]) => `  --${key}: ${pair[index]};`),
    ...Object.entries(tokens.line).map(([key, pair]) => `  --${key}: rgba(${pair[index].join(",")});`),
    ...Object.entries(tokens.ink).map(([key, { pair }]) => `  --${key}: ${pair[index]};`),
  ];
  return `${selector} {\n${values.join("\n")}\n}`;
};

const css = `/* Generated by npm run theme:generate from components/theme/tokens.json.
   UI roots own settled and animated values; the SVG world inherits neither. */
${block("[data-theme-root]", 0)}

${block(':root[data-theme="light"] [data-theme-root]', 1)}

/* Backing colors are literals, keeping palette variables out of the SVG. */
body { background: ${tokens.surface.bg[0]}; }
:root[data-theme="light"] body { background: ${tokens.surface.bg[1]}; }
`;
await writeFile(new URL("../app/theme.css", import.meta.url), css);
